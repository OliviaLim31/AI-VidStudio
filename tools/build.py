#!/usr/bin/env python3
"""Build a studio page for one project.

Usage:
  python tools/build.py projects/keyboard            -> dist/keyboard/ (index.html, css/, js/, fonts/)

The studio itself lives in studio/ (index.html + css/ + js/). The build copies it,
writes js/data.js with the fonts table and the project, and copies the project's
preview media (projects/<name>/media/, git-ignored) next to it.
"""
import json, os, shutil, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STUDIO = os.path.join(REPO, "studio")


def build(project_dir, out_dir=None):
    name = os.path.basename(os.path.normpath(project_dir))
    out_dir = out_dir or os.path.join(REPO, "dist", name)
    for sub in ("css", "js", "fonts"):
        shutil.copytree(os.path.join(STUDIO, sub), os.path.join(out_dir, sub), dirs_exist_ok=True)
    shutil.copy(os.path.join(STUDIO, "index.html"), out_dir)
    fonts = json.load(open(os.path.join(STUDIO, "fonts", "fonts.json"), encoding="utf-8"))
    project = json.load(open(os.path.join(project_dir, "project.json"), encoding="utf-8"))
    with open(os.path.join(out_dir, "js", "data.js"), "w", encoding="utf-8") as f:
        f.write("/* generated by tools/build.py */\n")
        f.write("const FONTS = " + json.dumps(fonts, ensure_ascii=False) + ";\n")
        f.write("const DEFAULT = " + json.dumps(project, ensure_ascii=False) + ";\n")
    for extra in ("media", "renders"):
        p = os.path.join(project_dir, extra)
        if os.path.isdir(p):
            shutil.copytree(p, os.path.join(out_dir, extra), dirs_exist_ok=True)
    print(f"built {out_dir}")
    return out_dir


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    build(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
